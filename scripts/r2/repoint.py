#!/usr/bin/env python3
"""Point the database rows at R2, without pasting SQL into the editor.

After the storage quota is lifted (Pro month or a support lift) the project API
works again, so the mapping generated by publish.py can be applied directly with
PostgREST: one PATCH per row, matched by content_hash, so ids and titles are
never touched.

Usage:
    python scripts/r2/repoint.py            # dry run: probe + counts
    python scripts/r2/repoint.py --execute  # apply
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def read_env() -> dict[str, str]:
    env: dict[str, str] = {}
    for path in (ROOT / "exam-library-admin" / ".env", ROOT / ".env", HERE / ".env"):
        if not path.exists():
            continue
        for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            env.setdefault(key.strip(), value.strip().strip('"').strip("'"))
    return env


def rest(url: str, key: str, method: str, path: str, payload: dict | None = None,
         prefer: str = "return=minimal") -> tuple[int, bytes]:
    body = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(
        url + "/rest/v1" + path, data=body, method=method,
        headers={"apikey": key, "Authorization": f"Bearer {key}",
                 "Content-Type": "application/json", "Prefer": prefer},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return resp.status, resp.read()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read()
    except Exception as exc:  # noqa: BLE001
        return 0, str(exc).encode()


def main() -> int:
    ap = argparse.ArgumentParser(description="Re-point Supabase rows at R2")
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--concurrency", type=int, default=8)
    args = ap.parse_args()

    sys.path.insert(0, str(HERE))
    import publish  # noqa: E402

    publish.load_env()
    env = read_env()
    url = (env.get("VITE_SUPABASE_URL") or "").rstrip("/")
    key = env.get("VITE_SUPABASE_SERVICE_ROLE_KEY") or ""
    base = (env.get("R2_PUBLIC_URL") or "").rstrip("/")
    if not url or not key or not base:
        sys.exit("need VITE_SUPABASE_URL, VITE_SUPABASE_SERVICE_ROLE_KEY and R2_PUBLIC_URL")

    papers, books, _, _ = publish.build(base, False, layout="supabase")
    print(f"mapping: {len(papers)} papers, {len(books)} books")

    code, body = rest(url, key, "GET", "/exam_papers?select=id&limit=1")
    if code != 200:
        detail = body[:200].decode("utf-8", "replace")
        print(f"\n! database not reachable: {code} {detail}")
        if code == 402:
            print("  the project is still restricted — upgrade or wait for the lift")
        return 1
    print("database reachable")

    for table, rows, extra in (("exam_papers", papers, "preview_url"),
                               ("library_books", books, "cover_url")):
        code, body = rest(url, key, "GET", f"/{table}?select=id&file_url=like.*r2.dev*",
                          prefer="count=exact")
        already = 0
        if code == 200:
            total = json.loads(body)
            already = len(total)
        print(f"{table}: {already} rows already on R2")

    if not args.execute:
        print("\ndry run. Re-run with --execute once the project responds.")
        return 0

    jobs = []
    for table, rows, extra in (("exam_papers", papers, "preview_url"),
                               ("library_books", books, "cover_url")):
        for row in rows:
            payload = {"file_url": row["file_url"]}
            if row.get(extra):
                payload[extra] = row[extra]
            jobs.append((table, row["content_hash"], payload, row.get("id")))

    done = {"ok": 0, "missing": 0, "failed": []}

    def apply(job):
        table, digest, payload, rid = job
        code, body = rest(url, key, "PATCH", f"/{table}?content_hash=eq.{digest}", payload)
        if code in (200, 204):
            done["ok"] += 1
            if done["ok"] % 50 == 0:
                print(f"  {done['ok']}/{len(jobs)}", flush=True)
        elif code == 404 or b"0 rows" in body:
            done["missing"] += 1
        else:
            done["failed"].append(f"{table} {rid}: {code} {body[:120].decode('utf-8','replace')}")

    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        list(pool.map(apply, jobs))

    print(f"\nupdated {done['ok']}  no matching row {done['missing']}  "
          f"failed {len(done['failed'])}")
    for line in done["failed"][:10]:
        print(f"  ! {line}")

    for table in ("exam_papers", "library_books"):
        code, body = rest(url, key, "GET", f"/{table}?select=id&file_url=like.*r2.dev*")
        on_r2 = len(json.loads(body)) if code == 200 else "?"
        code, body = rest(url, key, "GET", f"/{table}?select=id&file_url=like.*supabase.co*")
        on_sb = len(json.loads(body)) if code == 200 else "?"
        print(f"{table}: {on_r2} on R2, {on_sb} still on Supabase")
    return 0


if __name__ == "__main__":
    sys.exit(main())
